// Writes the project cards from js/projects.js straight into index.html, and regenerates
// sitemap.xml, so search engines (Bing especially) see every project without running JavaScript.
// js/main.js still draws the cards in the browser from js/projects.js, so the page works even if
// this wasn't re-run, but crawlers only see what's in the HTML.
//
// Run after changing js/projects.js:   node scripts/build-home.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = fileURLToPath(new URL("..", import.meta.url));
const BASE_DOMAIN = "dreamteamhub.ca";

const sandbox = { window: {} };
vm.runInNewContext(readFileSync(root + "js/projects.js", "utf8"), sandbox);
const projects = sandbox.window.PROJECTS || [];

const esc = (s) =>
  String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);
const projectUrl = (p) => p.url || `https://${p.subdomain}.${BASE_DOMAIN}`;

// Same markup as createCard() / createComingSoonCard() in js/main.js.
const indent = "      ";
const cards = projects.map((p) => [
  `<a class="card" href="${esc(projectUrl(p))}" aria-label="${esc(p.title + " ~ " + p.description)}">`,
  `  <div class="card__media">`,
  ...(p.image ? [`    <img src="${esc(p.image)}" alt="" loading="lazy" decoding="async">`] : []),
  `    <div class="card__overlay"><p class="card__description">${esc(p.description)}</p></div>`,
  `  </div>`,
  `  <h2 class="card__title">${esc(p.title)}</h2>`,
  `</a>`,
].map((l) => indent + l).join("\n"));
cards.push([
  `<div class="card card--soon">`,
  `  <div class="card__media">More coming soon</div>`,
  `  <h2 class="card__title">Stay tuned</h2>`,
  `</div>`,
].map((l) => indent + l).join("\n"));

const START = "<!-- projects:start (generated by scripts/build-home.mjs from js/projects.js) -->";
const END = "<!-- projects:end -->";
const indexPath = root + "index.html";
const html = readFileSync(indexPath, "utf8");
const a = html.indexOf(START), b = html.indexOf(END);
if (a < 0 || b < a) throw new Error("index.html is missing the projects:start / projects:end markers");
writeFileSync(indexPath, (html.slice(0, a + START.length) + "\n" + cards.join("\n") + "\n      " + html.slice(b))
  // The footer year, for crawlers too (js/main.js keeps it current in the browser).
  .replace(/<span id="year">\d*<\/span>/, `<span id="year">${new Date().getFullYear()}</span>`));

// Only pages on dreamteamhub.ca itself: a sitemap may only list URLs on its own host.
// The games' own sites are linked from the home page, which is how crawlers find them.
const d = new Date();
const today = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
const pages = ["/", "/contact.html", "/privacy.html"];
writeFileSync(root + "sitemap.xml",
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
  pages.map((p) => `  <url><loc>https://${BASE_DOMAIN}${p}</loc>${p === "/" ? `<lastmod>${today}</lastmod>` : ""}</url>`).join("\n") +
  `\n</urlset>\n`);

console.log(`index.html: ${projects.length} projects; sitemap.xml: ${pages.length} pages`);
